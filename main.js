function clearErrors(form) {
  form.querySelectorAll('.form-error').forEach(e => e.textContent = '');
  form.querySelectorAll('.input-error').forEach(e => e.classList.remove('input-error'));
}

function setError(input, message) {
  input.classList.add('input-error');
  const errorEl = input.closest('.form-group')?.querySelector('.form-error');
  if (errorEl) errorEl.textContent = message;
}

function validateForm(form) {
  clearErrors(form);
  let valid = true;
  const requiredMsg = currentLang === 'fr' ? 'Champ requis' : 'This field is required';

  const requiredFields = [
    'f-name', 'f-email', 'f-phone', 'f-jobfunction',
    'f-experience', 'f-qualification', 'f-skills', 'f-salary'
  ];

  requiredFields.forEach(id => {
    const input = document.getElementById(id);
    if (input && !input.value.trim()) {
      setError(input, requiredMsg);
      valid = false;
    }
  });

  const emailInput = document.getElementById('f-email');
  if (emailInput.value.trim() && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(emailInput.value.trim())) {
    setError(emailInput, currentLang === 'fr' ? 'Email invalide' : 'Invalid email');
    valid = false;
  }

  if (!fileInput.files[0]) {
    const cvGroup = fileInput.closest('.form-group');
    const errorEl = cvGroup?.querySelector('.form-error');
    if (errorEl) errorEl.textContent = currentLang === 'fr' ? 'CV requis' : 'CV is required';
    valid = false;
  }

  return valid;
}

