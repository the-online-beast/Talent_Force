// ============================================================
function loadJobs() {
  const loading = document.getElementById('jobsLoading');
  const errorEl = document.getElementById('jobsError');
  const empty   = document.getElementById('jobsEmpty');

  loading.style.display = 'block';
  errorEl.style.display = 'none';
  empty.style.display = 'none';

  fetch(SHEET_URL)
    .then(res => {
      if (!res.ok) throw new Error('Network error');
      return res.text();
    })
    .then(csvText => {
      allJobs = parseCSV(csvText);
      window.allJobs = allJobs;

      // Filtrer uniquement les offres actives si un statut existe
      const activeJobs = allJobs.filter(j => {
        const status = (j['Status'] || j['Statut'] || '').toLowerCase();
        return !status || status === 'active' || status === 'actif' || status === 'open';
      });

      allJobs = activeJobs;
      window.allJobs = allJobs;

      populateTypeFilter(allJobs);
      renderCards(allJobs);
    })
    .catch(err => {
      console.error('Erreur chargement jobs:', err);
      loading.style.display = 'none';
      errorEl.style.display = 'block';
    });
}

