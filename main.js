function populateTypeFilter(jobs) {
  const sel = document.getElementById('filterType');
  const existingOptions = sel.querySelectorAll('option:not([data-i18n])');
  existingOptions.forEach(o => o.remove());

  const types = [...new Set(jobs.map(j => j['Contract type']).filter(Boolean))];
  types.forEach(t => {
    const opt = document.createElement('option');
    opt.value = t;
    opt.textContent = t;
    sel.appendChild(opt);
  });
}

function renderCards(jobs) {
  const grid    = document.getElementById('jobsGrid');
  const loading = document.getElementById('jobsLoading');
  const empty   = document.getElementById('jobsEmpty');
  const errorEl = document.getElementById('jobsError');

  loading.style.display = 'none';
  errorEl.style.display = 'none';

  if (!jobs.length) {
    empty.style.display = 'block';
    grid.innerHTML = '';
    return;
  }
  empty.style.display = 'none';

  grid.innerHTML = jobs.map((job, idx) => {
    const title    = escapeHtml(job['Job Title'] || job['Title'] || '');
    const type     = escapeHtml(job['Contract type'] || '');
    const city     = escapeHtml(job['City'] || job['Location'] || '');
    const school   = escapeHtml(job['School'] || job['Company'] || '');
    const salary   = escapeHtml(job['Salary'] || '');

    return `
      <div class="job-card" data-idx="${idx}">
        <div class="job-card__top">
          <span class="job-card__title">${title}</span>
          ${type ? `<span class="job-card__type">${type}</span>` : ''}
        </div>
        <div class="job-card__meta">
          ${city ? `<span class="job-card__location">
            <svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
              <path d="M21 10c0 7-9 13-9 13s-9-6-9-13a9 9 0 0 1 18 0z"/>
              <circle cx="12" cy="10" r="3"/>
            </svg>
            ${city}
          </span>` : ''}
          ${school ? `<span class="job-card__school">${school}</span>` : ''}
          ${salary ? `<span class="job-card__salary">${salary}</span>` : ''}
        </div>
        <div class="job-card__cta">${currentLang === 'fr' ? 'Voir l\'offre →' : 'View job →'}</div>
      </div>
    `;
  }).join('');

  document.querySelectorAll('.job-card').forEach(card => {
    card.addEventListener('click', () => {
      const idx = parseInt(card.dataset.idx, 10);
      openJobDetail(jobs[idx]);
    });
  });

  document.getElementById('vacanciesCount').textContent =
    currentLang === 'fr'
      ? `${jobs.length} poste${jobs.length > 1 ? 's' : ''} disponible${jobs.length > 1 ? 's' : ''}`
      : `${jobs.length} position${jobs.length > 1 ? 's' : ''} available`;
}

let selectedJob = null;

function openJobDetail(job) {
  selectedJob = job;

  const title    = job['Job Title'] || job['Title'] || '';
  const type     = job['Contract type'] || '';
  const city     = job['City'] || job['Location'] || '';
  const school   = job['School'] || job['Company'] || '';
  const salary   = job['Salary'] || '';
  const longDesc = job['Description'] || job['Long Description'] || '';
  const reqs     = job['Requirements'] || '';
  const jdUrl    = job['JD URL'] || job['JD Link'] || '';

  document.getElementById('jd-title').textContent         = title;
  document.getElementById('jd-type').textContent          = type;
  document.getElementById('jd-location-text').textContent = city;
  document.getElementById('jd-salary-text').textContent   = salary;
  document.getElementById('jd-school').textContent        = school;
  document.getElementById('jd-description').innerHTML     = formatText(longDesc);
  document.getElementById('jd-requirements').innerHTML    = formatText(reqs);

  const downloadBtn = document.getElementById('download-jd-btn');
  if (downloadBtn) {
    if (jdUrl) {
      downloadBtn.href = toDriveDownloadLink(jdUrl);
      downloadBtn.style.display = 'inline-flex';
    } else {
      downloadBtn.style.display = 'none';
    }
  }

  openModal(jobModal);
}

