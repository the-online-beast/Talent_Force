function applyFilters() {
  const search = document.getElementById('filterSearch')?.value.trim().toLowerCase() || '';
  const type   = document.getElementById('filterType')?.value || '';

  const filtered = allJobs.filter(job => {
    const title  = (job['Job Title'] || job['Title'] || '').toLowerCase();
    const city   = (job['City'] || job['Location'] || '').toLowerCase();
    const school = (job['School'] || job['Company'] || '').toLowerCase();
    const jType  = job['Contract type'] || '';

    const matchesSearch = !search ||
      title.includes(search) || city.includes(search) || school.includes(search);
    const matchesType = !type || jType === type;

    return matchesSearch && matchesType;
  });

  renderCards(filtered);
}

